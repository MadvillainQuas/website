/* ============================================================================
   Does boxscore.js stand on its own?

     node supabase/tests/boxscore.isolation.mjs

   The extraction pulls functions out of a 3,400-line page where every helper
   is a global. Miss one and the module still loads, still passes a parity test
   run *inside the scorer* — because the scorer supplies the missing name — and
   then throws the moment the public page renders. That is exactly how `tname`
   got through.

   So this runs the module in a bare VM with nothing in scope but S and
   derive(), the two the module documents as required, and calls every renderer
   against a real game. Any other free identifier throws a ReferenceError here
   instead of on the site.
   ============================================================================ */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(new URL('../..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  cond ? pass++ : fail++;
  console.log(`  ${cond ? 'PASS' : 'FAIL'}  ${name}${extra ? '  -> ' + extra : ''}`);
};

/* A real game. Any finished game from the seeded season serves; the fixture is
   generated by the scorer itself, so it exercises shot locations, tags, shot
   types, substitutions, fouls and free throws — the parts with the most
   helpers behind them. */
const FIXTURE = path.join(ROOT, 'supabase', 'tests', 'fixtures', 'game.json');
if (!fs.existsSync(FIXTURE)) {
  console.log('\n  SKIP  no fixture at supabase/tests/fixtures/game.json');
  console.log('        Generate one from the scorer and the isolation test runs.\n');
  process.exit(0);
}
const game = JSON.parse(fs.readFileSync(FIXTURE, 'utf8'));

console.log('\nboxscore.js isolation —', game.teams[0].name, 'v', game.teams[1].name, '\n');

/* nothing in this sandbox but the two documented globals */
const sandbox = { S: game, console, module: undefined };
sandbox.self = sandbox;
sandbox.globalThis = sandbox;
const ctx = vm.createContext(sandbox);

vm.runInContext(read('epinoia/engine.js'), ctx, { filename: 'engine.js' });
sandbox.derive = () => sandbox.EpinoiaEngine.deriveGame(sandbox.S);
vm.runInContext(read('epinoia/boxscore.js'), ctx, { filename: 'boxscore.js' });

const B = sandbox.EpinoiaBox;
if (B && B.rebuildPmap) B.rebuildPmap();   // the viewer does this after setting S
ok('module exports', !!B && typeof B === 'object', B ? Object.keys(B).length + ' symbols' : 'missing');

const d = sandbox.derive();
ok('replay produces a score', Array.isArray(d.score) && d.score[0] + d.score[1] > 0,
   d.score && d.score.join('-'));

/* every renderer the public page calls, exactly as it calls them */
const CALLS = [
  ['scoreHeadHTML',  () => B.scoreHeadHTML(d)],
  ['qstripHTML',     () => B.qstripHTML(d)],
  ['bxTeamHTML home',() => B.bxTeamHTML(d, 0)],
  ['bxTeamHTML away',() => B.bxTeamHTML(d, 1)],
  ['teamChipsHTML',  () => B.teamChipsHTML(d, 0)],
  ['pbpHTML',        () => B.pbpHTML(d)],
  ['shotChartHTML 0',() => B.shotChartHTML(d, 0)],
  ['shotChartHTML 1',() => B.shotChartHTML(d, 1)],
  ['advHTML',        () => B.advHTML(d)],
  ['lineupsHTML',    () => B.lineupsHTML()]
];

for (const [name, fn] of CALLS) {
  try {
    const html = fn();
    ok(name, typeof html === 'string' && html.length > 0, html.length + ' chars');
  } catch (e) {
    ok(name, false, e.constructor.name + ': ' + e.message);
  }
}

/* the box score must actually name the players, not just count them */
try {
  const html = B.bxTeamHTML(d, 0);
  const first = game.teams[0].players[0];
  ok('box score names players', html.includes(first.name), first.name);
  ok('box score shows jerseys', html.includes('>' + first.num + '<'), '#' + first.num);
} catch (e) { ok('box score content', false, e.message); }

console.log(`\n${pass} passed, ${fail} failed\n`);
process.exitCode = fail ? 1 : 0;
